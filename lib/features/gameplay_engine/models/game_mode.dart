/// Defines the different game modes available in Soteria.
enum GameMode {
  /// Unlimited time, focused on learning.
  practice,

  /// Standard competitive rules with standard scoring.
  pro,

  /// Head-to-head match against another player.
  versus,

  /// Large scale organized competition.
  tournament,

  /// Specific thematic or difficulty-based tasks.
  challenge,

  /// Daily unique set of questions.
  dailyQuiz,

  /// Temporary competitive events.
  event,
}
